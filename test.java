/*
 * ============================================================
 * Java 泛型通配符（Wildcard）知识点总结
 * ============================================================
 *
 * 一、为什么需要通配符？
 *
 * Java 泛型是不支持继承关系的。
 *
 * 例如：
 *
 * Integer 是 Number 的子类：
 *
 * Integer extends Number
 *
 * 但是：
 *
 * List<Integer>
 *        |
 *        | 不是继承关系
 *        ↓
 * List<Number>
 *
 *
 * 所以以下代码错误：
 *
 * List<Integer> list1 = new ArrayList<>();
 *
 * List<Number> list2 = list1;
 *
 *
 * 原因：
 *
 * 如果允许：
 *
 * list2.add(3.14);
 *
 * 那么实际上向 List<Integer> 中添加了 Double 类型数据，
 * 会破坏泛型的类型安全。
 *
 *
 * 为了解决泛型类型不确定的问题，
 * Java 提供了通配符：
 *
 * ?
 *
 *
 *
 * ============================================================
 * 二、无界通配符 ?
 * ============================================================
 *
 * 1. 概念：
 *
 * ? 表示未知类型（任意类型）
 *
 *
 * 例如：
 *
 * List<?> list;
 *
 *
 * 可以接收：
 *
 * List<String>
 *
 * List<Integer>
 *
 * List<Double>
 *
 *
 * 任何泛型 List 都可以赋值给 List<?>。
 *
 *
 * 示例：
 *
 * List<?> list1 = new ArrayList<String>();
 *
 * List<?> list2 = new ArrayList<Integer>();
 *
 *
 *
 * ============================================================
 * 三、List<?> 的特点
 * ============================================================
 *
 * 1. 可以读取数据
 *
 * 因为不知道具体类型，
 * 所以读取出来只能当 Object。
 *
 *
 * 示例：
 *
 * List<?> list = new ArrayList<String>();
 *
 * Object obj = list.get(0);
 *
 *
 *
 * 2. 不能添加数据
 *
 * 错误：
 *
 * list.add("hello");
 *
 *
 * 原因：
 *
 * 编译器不知道真实类型：
 *
 * 可能是：
 *
 * List<String>
 *
 * 也可能是：
 *
 * List<Integer>
 *
 *
 * 如果允许添加，会破坏类型安全。
 *
 *
 * 但是：
 *
 * 可以添加 null
 *
 * list.add(null);
 *
 *
 *
 * 使用场景：
 *
 * 当方法只需要遍历数据，
 * 不关心具体类型时使用。
 *
 *
 * 示例：
 *
 * public void print(List<?> list){
 *
 *     for(Object obj : list){
 *
 *         System.out.println(obj);
 *
 *     }
 *
 * }
 *
 *
 *
 * ============================================================
 * 四、上限通配符 ? extends
 * ============================================================
 *
 * 1. 格式：
 *
 * ? extends 类型
 *
 *
 * 例如：
 *
 * List<? extends Number>
 *
 *
 * 表示：
 *
 * 泛型类型必须是 Number 或 Number 的子类。
 *
 *
 * 可以匹配：
 *
 * List<Integer>
 *
 * List<Double>
 *
 * List<Float>
 *
 *
 * 不可以匹配：
 *
 * List<String>
 *
 *
 *
 * 关系：
 *
 *             Number
 *              |
 *     -----------------
 *     |       |       |
 * Integer Double  Float
 *
 *
 *
 * ============================================================
 * 五、extends 的读取规则
 * ============================================================
 *
 * 核心：
 *
 * extends 可以读取，不能添加。
 *
 *
 * 示例：
 *
 * List<? extends Number> list;
 *
 *
 * 读取：
 *
 * Number num = list.get(0);
 *
 * 正确。
 *
 *
 * 原因：
 *
 * 不管实际类型是什么：
 *
 * Integer
 * Double
 * Float
 *
 *
 * 他们都是 Number 的子类，
 * 所以可以安全向上转型。
 *
 *
 *
 * ============================================================
 * 六、extends 为什么不能添加？
 * ============================================================
 *
 * 假设：
 *
 * List<? extends Number> list;
 *
 *
 * 实际类型可能是：
 *
 * List<Integer>
 *
 *
 * 如果允许：
 *
 * list.add(3.14);
 *
 *
 * 那么：
 *
 * Double
 *
 * 被添加到了：
 *
 * List<Integer>
 *
 *
 * 类型被破坏。
 *
 *
 * 所以：
 *
 * list.add(任何具体对象);
 *
 * 都不允许。
 *
 *
 * 唯一允许：
 *
 * list.add(null);
 *
 *
 *
 * ============================================================
 * 七、下限通配符 ? super
 * ============================================================
 *
 * 1. 格式：
 *
 * ? super 类型
 *
 *
 * 例如：
 *
 * List<? super Integer>
 *
 *
 * 表示：
 *
 * 泛型类型必须是 Integer
 * 或 Integer 的父类。
 *
 *
 * 可以匹配：
 *
 * List<Integer>
 *
 * List<Number>
 *
 * List<Object>
 *
 *
 *
 * 类型关系：
 *
 * Object
 *   |
 * Number
 *   |
 * Integer
 *
 *
 *
 * ============================================================
 * 八、super 的添加规则
 * ============================================================
 *
 * 核心：
 *
 * super 可以添加，读取只能 Object。
 *
 *
 * 示例：
 *
 * List<? super Integer> list;
 *
 *
 * 添加：
 *
 * list.add(100);
 *
 * 正确。
 *
 *
 * 因为：
 *
 * 无论实际类型：
 *
 * List<Integer>
 *
 * List<Number>
 *
 * List<Object>
 *
 *
 * 都可以存储 Integer。
 *
 *
 *
 * ============================================================
 * 九、super 为什么读取只能 Object？
 * ============================================================
 *
 * 假设：
 *
 * List<? super Integer> list;
 *
 *
 * 实际可能是：
 *
 * List<Object>
 *
 *
 * Object 中可以存：
 *
 * String
 * Integer
 * Double
 *
 *
 * 所以：
 *
 * Integer i = list.get(0);
 *
 * 不安全。
 *
 *
 * 只能：
 *
 * Object obj = list.get(0);
 *
 *
 *
 * ============================================================
 * 十、extends 和 super 对比
 * ============================================================
 *
 *
 *              extends              super
 *
 * 中文：       上限通配符          下限通配符
 *
 * 方向：       子类方向            父类方向
 *
 * 读取：       可以                只能Object
 *
 * 添加：       不可以              可以
 *
 * 用途：       生产数据            消费数据
 *
 *
 *
 *
 * ============================================================
 * 十一、PECS原则（重点）
 * ============================================================
 *
 * PECS：
 *
 * Producer Extends
 *
 * Consumer Super
 *
 *
 * 中文：
 *
 * 生产者使用 extends
 *
 * 消费者使用 super
 *
 *
 *
 * 1. Producer（生产者）
 *
 * 数据来源于集合：
 *
 * 只读取，不修改
 *
 * 使用：
 *
 * ? extends
 *
 *
 * 示例：
 *
 * List<? extends Number>
 *
 *
 *
 * 2. Consumer（消费者）
 *
 * 集合接收外部数据：
 *
 * 只写入
 *
 * 使用：
 *
 * ? super
 *
 *
 * 示例：
 *
 * List<? super Integer>
 *
 *
 *
 * ============================================================
 * 十二、实际开发中的使用
 * ============================================================
 *
 *
 * 1. 方法参数接收任意类型：
 *
 * public void print(List<?> list){
 *
 * }
 *
 *
 *
 * 2. 读取数字类型：
 *
 * public double sum(
 *        List<? extends Number> list
 * ){
 *
 * }
 *
 *
 *
 * 3. 添加数据：
 *
 * public void addNumber(
 *        List<? super Integer> list
 * ){
 *
 *     list.add(10);
 *
 * }
 *
 *
 *
 * ============================================================
 * 十三、面试总结
 * ============================================================
 *
 *
 * 1. ? 表示未知类型
 *
 * 2. List<?> 可以接收任意泛型集合
 *
 * 3. ? extends T：
 *
 *    - T及其子类
 *    - 可以读取
 *    - 不能添加
 *
 *
 * 4. ? super T：
 *
 *    - T及其父类
 *    - 可以添加T类型数据
 *    - 读取只能Object
 *
 *
 * 5. 泛型没有继承关系，
 *    通配符用于解决泛型兼容问题。
 *
 *
 * 6. 记忆：
 *
 *    extends = 读取
 *
 *    super = 写入
 *
 *    PECS：
 *    Producer Extends
 *    Consumer Super
 *
 *
 * ============================================================
 */
