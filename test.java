/*
 * ============================================================
 * Java 向上转型和向下转型总结
 * ============================================================
 *
 *
 * 一、类型转换的本质
 *
 * Java中的对象转换，本质不是改变对象本身，
 * 而是改变“引用看待对象的方式”。
 *
 *
 * 对象：
 *
 *       真正存在于内存中的对象
 *
 * 引用：
 *
 *       指向对象的变量
 *
 *
 * 例如：
 *
 * Dog dog = new Dog();
 *
 * 创建的是 Dog 对象。
 *
 * 转换：
 *
 * Animal animal = dog;
 *
 * 并不会把 Dog 变成 Animal。
 *
 * 实际：
 *
 *       对象仍然是 Dog
 *
 *       只是引用类型变成 Animal
 *
 *
 *
 * ============================================================
 * 二、向上转型（Upcasting）
 * ============================================================
 *
 * 定义：
 *
 * 子类对象转换为父类引用。
 *
 *
 * 格式：
 *
 * 父类类型  引用名 = 子类对象;
 *
 *
 * 示例：
 *
 * class Animal {
 *
 *     public void eat(){
 *
 *     }
 *
 * }
 *
 *
 * class Dog extends Animal {
 *
 *     public void bark(){
 *
 *     }
 *
 * }
 *
 *
 * Dog dog = new Dog();
 *
 * Animal animal = dog;
 *
 *
 *
 * ============================================================
 * 三、向上转型为什么安全？
 * ============================================================
 *
 * 因为：
 *
 * 子类一定包含父类所有的属性和方法。
 *
 *
 * 例如：
 *
 * Animal:
 *
 *    eat()
 *
 *
 * Dog:
 *
 *    eat()
 *    bark()
 *
 *
 * Dog对象一定拥有eat()方法。
 *
 *
 * 所以：
 *
 * Animal animal = new Dog();
 *
 * 调用：
 *
 * animal.eat();
 *
 * 一定安全。
 *
 *
 *
 * ============================================================
 * 四、向上转型的本质
 * ============================================================
 *
 * 不是对象变了。
 *
 * 而是：
 *
 * 隐藏子类特有能力，
 * 只暴露父类定义的能力。
 *
 *
 * 例如：
 *
 * Dog对象：
 *
 * +----------------+
 * | Animal部分     |
 * | eat()          |
 * +----------------+
 * | Dog部分        |
 * | bark()         |
 * +----------------+
 *
 *
 * Animal引用：
 *
 * 只能看到：
 *
 * +----------------+
 * | Animal部分     |
 * | eat()          |
 * +----------------+
 *
 *
 * bark()方法仍然存在，
 * 只是无法直接调用。
 *
 *
 *
 * ============================================================
 * 五、向上转型的特点
 * ============================================================
 *
 * 1. 自动完成
 *
 * 不需要强制转换：
 *
 * Animal animal = new Dog();
 *
 *
 *
 * 2. 安全
 *
 * 因为：
 *
 * 子类一定是父类。
 *
 *
 *
 * 3. 体现多态
 *
 *
 * Animal animal = new Dog();
 *
 * animal.eat();
 *
 *
 * 编译看Animal：
 *
 *    是否有eat方法
 *
 *
 * 运行看Dog：
 *
 *    执行Dog重写的方法
 *
 *
 *
 * ============================================================
 * 六、向下转型（Downcasting）
 * ============================================================
 *
 * 定义：
 *
 * 父类引用转换为子类引用。
 *
 *
 * 格式：
 *
 * 子类类型 引用名 = (子类类型)父类引用;
 *
 *
 * 示例：
 *
 * Animal animal = new Dog();
 *
 * Dog dog = (Dog) animal;
 *
 *
 *
 * ============================================================
 * 七、向下转型为什么需要强制转换？
 * ============================================================
 *
 * 因为：
 *
 * 父类不一定是某个子类。
 *
 *
 * 例如：
 *
 *        Animal
 *        /    \
 *      Dog    Cat
 *
 *
 * Animal animal;
 *
 *
 * 可能：
 *
 * animal = new Dog();
 *
 *
 * 也可能：
 *
 * animal = new Cat();
 *
 *
 * 所以：
 *
 * Dog dog = (Dog)animal;
 *
 * 存在风险。
 *
 *
 *
 * ============================================================
 * 八、向下转型的本质
 * ============================================================
 *
 * 向下转型是在告诉Java：
 *
 * “我确定这个父类引用指向的是某个子类对象”
 *
 *
 * 例如：
 *
 * Animal animal = new Dog();
 *
 * Dog dog = (Dog)animal;
 *
 *
 * 因为真实对象是Dog，
 * 所以转换成功。
 *
 *
 *
 * ============================================================
 * 九、向下转型失败情况
 * ============================================================
 *
 * 示例：
 *
 * Animal animal = new Cat();
 *
 * Dog dog = (Dog)animal;
 *
 *
 * 编译通过：
 *
 * 因为Animal和Dog存在继承关系。
 *
 *
 * 运行失败：
 *
 * ClassCastException
 *
 *
 * 原因：
 *
 * 实际对象不是Dog。
 *
 *
 *
 * ============================================================
 * 十、instanceof 防止转换异常
 * ============================================================
 *
 * 转换前判断：
 *
 * if(animal instanceof Dog){
 *
 *     Dog dog = (Dog)animal;
 *
 * }
 *
 *
 * instanceof：
 *
 * 判断对象是否属于某个类型。
 *
 *
 *
 * ============================================================
 * 十一、向上和向下转型对比
 * ============================================================
 *
 *
 *             向上转型        向下转型
 *
 * 方向：       子类->父类      父类->子类
 *
 * 是否自动：   是             否，需要强转
 *
 * 安全性：     安全           有风险
 *
 * 是否丢失能力：
 *
 *              子类特有方法不可见
 *
 *
 * 是否可能异常：
 *
 *              不会           可能ClassCastException
 *
 *
 *
 * ============================================================
 * 十二、核心记忆
 * ============================================================
 *
 *
 * 1. 子类一定是父类
 *
 *    Dog is Animal
 *
 *    所以：
 *
 *    Dog -> Animal
 *
 *    安全
 *
 *
 *
 * 2. 父类不一定是子类
 *
 *    Animal 不一定 Dog
 *
 *    所以：
 *
 *    Animal -> Dog
 *
 *    有风险
 *
 *
 *
 * 3. 转换改变的是引用类型，
 *    不改变对象本身。
 *
 *
 *
 * 4. 多态核心：
 *
 *    父类引用指向子类对象
 *
 *    Animal animal = new Dog();
 *
 *
 * ============================================================
 */